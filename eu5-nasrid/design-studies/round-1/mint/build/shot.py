import asyncio, sys
from playwright.async_api import async_playwright
OUT = sys.argv[1]; URL = 'file://' + sys.argv[2]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium_headless_shell-1243/chrome-headless-shell-linux64/chrome-headless-shell')
        pg = await b.new_page(viewport={'width':1280,'height':900})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
        await pg.goto(URL); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=OUT+'/s1-cabinet.png', full_page=True)
        await pg.click('.tcoin[data-i="18"]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT+'/s2-obverse.png')
        await pg.click('#pFlip'); await pg.wait_for_timeout(1000)
        await pg.screenshot(path=OUT+'/s3-reverse.png')
        await pg.goto(URL+'#1442-06-11'); await pg.wait_for_timeout(800)
        await pg.click('#pFlip'); await pg.wait_for_timeout(1000)
        await pg.screenshot(path=OUT+'/s4-rev1442.png')
        await pg.click('#pScale'); await pg.click('#pClose')
        await pg.click('.tcoin[data-i="12"]'); await pg.wait_for_timeout(300); await pg.click('#pScale'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT+'/s5-compare.png')
        await pg.click('#pClose')
        await pg.click('.drawer[data-r="yusuf-i"] [data-sort="purse"]'); await pg.wait_for_timeout(1200)
        await pg.click('.drawer[data-r="saad-ibn-yusuf"] .front'); await pg.wait_for_timeout(300)
        await pg.click('.drawer[data-r="saad-ibn-yusuf"] [data-thread]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=OUT+'/s6-sorted.png', full_page=True)
        m = await b.new_page(viewport={'width':390,'height':844}, device_scale_factor=2)
        await m.goto(URL); await m.wait_for_timeout(1200)
        await m.screenshot(path=OUT+'/m1.png')
        await m.click('.tcoin[data-i="20"]'); await m.wait_for_timeout(500)
        await m.screenshot(path=OUT+'/m2.png')
        sw = await m.evaluate('document.documentElement.scrollWidth')
        await m.click('#pClose'); await m.click('#bRub'); await m.wait_for_timeout(500)
        await m.screenshot(path=OUT+'/m3-rub.png', full_page=True)
        print('errors', errs, 'phone scrollWidth', sw)
        await b.close()
asyncio.run(main())
